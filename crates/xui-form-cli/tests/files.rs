#[test]
fn render_fails_cleanly_and_writes_nothing() {
    let dir = scratch("render-failures");
    let out = dir.join("out");
    let out_arg = out.to_string_lossy().into_owned();
    let render = |file: &str, extra: &[&str]| {
        let mut args = vec!["render", file, "--out", &out_arg];
        args.extend(extra);
        xui_form(&args)
    };

    // A file that is not there.
    let missing = dir.join("missing.lfm").to_string_lossy().into_owned();
    let output = render(&missing, &[]);
    assert_eq!(output.status.code(), Some(1));
    assert!(
        stderr(&output).contains("missing.lfm"),
        "{}",
        stderr(&output)
    );

    // A form that does not load: located.
    let broken = file(&dir, "broken.lfm", "Form(root: Button(txt: \"OK\"))");
    let output = render(&broken, &[]);
    assert_eq!(output.status.code(), Some(1));
    assert!(
        stderr(&output).contains("broken.lfm:1:19"),
        "{}",
        stderr(&output)
    );

    // A form that loads and is invalid: refused with its diagnostics.
    let invalid = file(
        &dir,
        "invalid.lfm",
        r#"Form(root: Column(children: [Button(name: "form"), Label(name: "a"), Label(name: "a")]))"#,
    );
    let output = render(&invalid, &[]);
    assert_eq!(output.status.code(), Some(1));
    let message = stderr(&output);
    assert!(
        message.contains("error: `form`: `form` is reserved"),
        "{message}"
    );
    assert!(message.contains("`a` is used more than once"), "{message}");
    assert!(message.contains("not rendered"), "{message}");

    // A window bigger than the renderer makes: 9000 > 8192 pixels.
    let wide = file(&dir, "wide.lfm", "Form(size: (9000, 100), root: Column())");
    let output = render(&wide, &[]);
    assert_eq!(output.status.code(), Some(1));
    assert!(
        stderr(&output).contains("at most 8192px a side"),
        "{}",
        stderr(&output)
    );

    // A DPI that is not a number is a usage error; one that is out of range
    // is refused.
    let hello = file(&dir, "hello.lfm", HELLO);
    let output = render(&hello, &["--dpi", "high"]);
    assert_eq!(output.status.code(), Some(2));
    assert!(stderr(&output).contains("`--dpi high` is not a number"));
    for dpi in ["0", "5000"] {
        let output = render(&hello, &["--dpi", dpi]);
        assert_eq!(output.status.code(), Some(1), "--dpi {dpi}");
        assert!(
            stderr(&output).contains("a DPI from 1 to"),
            "{}",
            stderr(&output)
        );
    }

    // Warnings do not stop a render.
    let warned = file(
        &dir,
        "warned.lfm",
        r#"Form(root: Column(children: [Button(name: "a", at: (0, 0, 10, 10))]))"#,
    );
    let output = render(&warned, &[]);
    assert!(output.status.success(), "{}", stderr(&output));
    assert!(stderr(&output).contains("warning: `a`: `at` only places"));

    assert_eq!(
        names_in(&out),
        ["warned-dark.png", "warned-light.png"],
        "only the form that could be rendered was"
    );
}

#[test]
fn schema_types_carry_no_macro_internals() {
    let output = xui_form(&["schema", "--json"]);
    let text = stdout(&output);
    assert!(!text.contains('$'), "a `$crate` leaked into the schema");
    assert!(!text.contains(",)"));
    let schema: serde_json::Value = serde_json::from_str(&text).expect("it is JSON");
    let at = schema["layout_fields"]
        .as_array()
        .and_then(|fields| fields.iter().find(|field| field["name"] == "at"))
        .expect("the `at` field");
    assert_eq!(at["ty"], "Option<(Length,Length,Length,Length)>");
}

#[test]
fn fmt_says_when_it_drops_a_comment() {
    let dir = scratch("fmt-comments");
    let commented = file(
        &dir,
        "commented.lfm",
        "// the greeting\nForm(title: \"http://example.com\", root: Column())\n",
    );
    let output = xui_form(&["fmt", &commented]);
    assert!(output.status.success());
    assert!(
        stderr(&output).contains("commented.lfm: note: comments are not kept"),
        "{}",
        stderr(&output)
    );
    assert_eq!(
        std::fs::read_to_string(&commented).expect("it reads"),
        "Form(title: \"http://example.com\", size: (320, 200), root: Column())\n"
    );

    // A `//` inside a string is not a comment.
    let plain = file(
        &dir,
        "plain.lfm",
        "Form(title:\"http://example.com\",root:Column())",
    );
    let output = xui_form(&["fmt", &plain]);
    assert!(output.status.success());
    assert!(stderr(&output).is_empty(), "{}", stderr(&output));
}

//! The tool's behaviour on awkward files and failures: unreadable files,
//! byte order marks, line endings, a format-1 file in disguise, and what is
//! left behind when a command fails.

mod common;

use std::path::Path;

use common::{HELLO, file, names_in, scratch, stderr, stdout, xui_form};

#[test]
fn check_goes_on_past_a_file_it_cannot_read() {
    let dir = scratch("check-unreadable");
    let good = file(&dir, "good.lfm", HELLO);
    let missing = dir.join("missing.lfm").to_string_lossy().into_owned();
    let broken = file(&dir, "broken.lfm", "Form(root: Button(txt: \"OK\"))");
    let not_utf8 = dir.join("binary.lfm");
    std::fs::write(&not_utf8, [0xff, 0xfe, 0x00, 0x01]).expect("the file is written");

    let output = xui_form(&[
        "check",
        &missing,
        &good,
        &not_utf8.to_string_lossy(),
        &broken,
    ]);
    assert_eq!(output.status.code(), Some(1));
    let report = stdout(&output);
    assert!(report.contains("missing.lfm: error:"), "{report}");
    assert!(
        report.contains("good.lfm: ok"),
        "checked after the missing file: {report}"
    );
    assert!(report.contains("binary.lfm: error:"), "{report}");
    assert!(report.contains("broken.lfm:1:19: error:"), "{report}");
}

#[test]
fn a_byte_order_mark_loads_and_fmt_removes_it() {
    let dir = scratch("bom");
    let marked = file(&dir, "marked.lfm", &format!("\u{feff}{HELLO}"));
    let output = xui_form(&["check", &marked]);
    assert!(output.status.success(), "{}", stdout(&output));

    let output = xui_form(&["fmt", "--check", &marked]);
    assert_eq!(output.status.code(), Some(1), "a BOM is not canonical");
    assert!(xui_form(&["fmt", &marked]).status.success());
    assert_eq!(std::fs::read_to_string(&marked).expect("it reads"), HELLO);
}

#[test]
fn crlf_line_endings_are_not_canonical_and_fmt_writes_lf() {
    let dir = scratch("crlf");
    let crlf = file(&dir, "crlf.lfm", &HELLO.replace('\n', "\r\n"));
    assert!(xui_form(&["check", &crlf]).status.success(), "it loads");
    let output = xui_form(&["fmt", "--check", &crlf]);
    assert_eq!(output.status.code(), Some(1));
    assert!(stdout(&output).contains("crlf.lfm: not formatted"));
    assert!(xui_form(&["fmt", &crlf]).status.success());
    assert_eq!(std::fs::read_to_string(&crlf).expect("it reads"), HELLO);
}

#[test]
fn the_shipped_example_forms_are_canonical() {
    // `.gitattributes` keeps `*.lfm` LF in a Windows checkout, which is what
    // makes this byte comparison true there too.
    let forms = Path::new(env!("CARGO_MANIFEST_DIR")).join("../xui/examples/forms");
    for name in ["login.lfm", "calculator.lfm"] {
        let path = forms.join(name).to_string_lossy().into_owned();
        let output = xui_form(&["fmt", "--check", &path]);
        assert!(
            output.status.success(),
            "{name} is not canonical: {}",
            stdout(&output)
        );
    }
}

#[test]
fn fmt_leaves_a_file_it_cannot_read_untouched_and_no_temporary_behind() {
    let dir = scratch("fmt-untouched");
    let broken_text = "Form(root: Column(children: [Button(txt: \"OK\")]))";
    let broken = file(&dir, "broken.lfm", broken_text);
    let output = xui_form(&["fmt", &broken]);
    assert_eq!(output.status.code(), Some(1));
    assert!(
        stderr(&output).contains("broken.lfm:1:"),
        "{}",
        stderr(&output)
    );
    assert_eq!(
        std::fs::read_to_string(&broken).expect("it reads"),
        broken_text
    );
    assert_eq!(names_in(&dir), ["broken.lfm"]);

    // A successful write is the one file, whole: no temporary is left.
    let messy = file(
        &dir,
        "messy.lfm",
        "Form(title:\"Hello\",size:(240,120),root:Column())",
    );
    assert!(xui_form(&["fmt", &messy]).status.success());
    assert_eq!(names_in(&dir), ["broken.lfm", "messy.lfm"]);
}

#[test]
fn migrate_will_not_overwrite_its_own_input() {
    let dir = scratch("migrate-in-place");
    let v1_text = "format = 1\n[window]\nname = \"old\"\n";
    let v1 = file(&dir, "old.lfm", v1_text);
    // The same file, spelt two ways.
    let alias = dir.join(".").join("old.lfm").to_string_lossy().into_owned();
    for out in [v1.clone(), alias] {
        let output = xui_form(&["migrate", &v1, "--out", &out]);
        assert_eq!(output.status.code(), Some(1));
        assert!(
            stderr(&output).contains("refusing to overwrite"),
            "{}",
            stderr(&output)
        );
    }
    assert_eq!(std::fs::read_to_string(&v1).expect("it reads"), v1_text);
    assert_eq!(names_in(&dir), ["old.lfm"]);
}

